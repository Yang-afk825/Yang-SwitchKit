"""AI 能力：自然语言填参数 + 配置语法校对 + 在线语义补充。

和 `scg.audit` 的分工
--------------------
两个模块都在看「用户粘进来的这段配置」，但看的不是一回事：

* ``audit.py`` 查的是**安全**：SNMP 团体名是不是 public、VLAN1 有没有拿来
  做管理、配没配 NTP、空闲端口关没关。视角是等保测评和项目验收。
* ``rules.py`` 查的是**语法与结构**：``port link-type`` 跑没跑在接口视图里、
  基础 ACL 是不是带了协议字段、锐捷配了 SSH 却没开服务端、端口编号符不符合
  厂商惯例、以及拼错的关键字。
* 在线语义层补的是**意图**：两段配置互相冲突、缺配套命令、策略顺序。

三层叠在「配置体检」页上，先看安不安全，再看能不能跑，最后看合不合理。

这个包的存在不影响离线使用
------------------------
``scg/ai/`` 里没有任何模块在启动时被导入。界面层用「点了才 import」的方式
加载它，所以没配置 key 的用户启动耗时和以前一样，把这个包整个删掉主程序
也照样跑。

红线：没有任何一个模块会输出配置命令。模型只填参数，命令永远由
``registry`` + ``vendors`` 按模板生成。详见 docs/AI-MODE.md 第一节。
"""
